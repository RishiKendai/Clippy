import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

/// Converts between the live pasteboard and stored snapshots, and derives what a clip
/// looks like in the list (kind, plain text, thumbnail, duplicate hash).
public enum PasteboardCodec {
    /// Clips larger than this (all formats together) are not recorded.
    public static let defaultMaxBytes = 50 * 1024 * 1024

    /// nspasteboard.org markers that password managers and similar apps set.
    public static let secretMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Types that can't be faithfully stored and written back (promises, dynamic types).
    static func isStorable(_ uti: String) -> Bool {
        if uti.hasPrefix("dyn.") { return false }
        if uti.localizedCaseInsensitiveContains("promise") { return false }
        if uti == "com.apple.NSFilePromiseItemMetaData" { return false }
        return true
    }

    public static func hasSecretMarker(_ pasteboard: NSPasteboard) -> Bool {
        let types = (pasteboard.types ?? []).map(\.rawValue)
        return types.contains { secretMarkers.contains($0) }
    }

    // MARK: Pasteboard ⇄ snapshot

    /// Reads every type of every item. Returns nil if empty or larger than `maxBytes`.
    public static func read(_ pasteboard: NSPasteboard, maxBytes: Int = defaultMaxBytes) -> PasteboardSnapshot? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        var reps: [Representation] = []
        var total = 0
        for (index, item) in items.enumerated() {
            for type in item.types where isStorable(type.rawValue) {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > maxBytes { return nil }
                reps.append(Representation(itemIndex: index, uti: type.rawValue, data: data))
            }
        }
        return reps.isEmpty ? nil : PasteboardSnapshot(reps)
    }

    /// Replaces the pasteboard's contents with the snapshot, every item and type as stored.
    /// Returns the pasteboard's new change count.
    @discardableResult
    public static func write(_ snapshot: PasteboardSnapshot, to pasteboard: NSPasteboard) -> Int {
        let items: [NSPasteboardItem] = snapshot.items.map { reps in
            let item = NSPasteboardItem()
            for rep in reps {
                item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.uti))
            }
            return item
        }
        pasteboard.clearContents()
        pasteboard.writeObjects(items)
        return pasteboard.changeCount
    }

    /// Replaces the pasteboard's contents with plain text only. Returns the new change count.
    @discardableResult
    public static func writePlain(_ text: String, to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        return pasteboard.changeCount
    }

    // MARK: Analysis

    /// Works out how a snapshot is shown and deduplicated. Returns nil when there is nothing
    /// Clippy can show (no text, image or file), e.g. app-private data only.
    public static func analyze(_ snapshot: PasteboardSnapshot) -> AnalyzedClip? {
        let fileURLs = snapshot.representations
            .filter { $0.uti == NSPasteboard.PasteboardType.fileURL.rawValue }
            .compactMap { URL(dataRepresentation: $0.data, relativeTo: nil) }
            .filter(\.isFileURL)
        if !fileURLs.isEmpty {
            let paths = fileURLs.map(\.path).joined(separator: "\n")
            // Image files (e.g. copied in Finder) are shown as the image, not their name.
            // Pasting still pastes the files themselves; the path stays searchable.
            if fileURLs.allSatisfy(isImageFile), let thumb = thumbnail(fileURL: fileURLs[0]) {
                return AnalyzedClip(kind: .image, plainText: paths, hash: digest("file|" + paths), thumbnail: thumb, snapshot: snapshot)
            }
            return AnalyzedClip(kind: .file, plainText: paths, hash: digest("file|" + paths), thumbnail: nil, snapshot: snapshot)
        }

        let text = plainText(from: snapshot)?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let image = primaryImage(in: snapshot)

        // An image whose only text is its own name or URL (e.g. "Copy Image" in a browser) is an image.
        if let image, text.isEmpty || looksLikeImageReference(text), let thumb = thumbnail(from: image.data) {
            return AnalyzedClip(kind: .image, plainText: text, hash: digest(image.data, prefix: "image|"), thumbnail: thumb, snapshot: snapshot)
        }

        if !text.isEmpty, let fullText = plainText(from: snapshot) {
            // Exactly the same text (spaces, newlines and case included) = same clip; the newest
            // copy's formats replace the old ones.
            return AnalyzedClip(kind: .text, plainText: fullText, hash: digest("text|" + fullText), thumbnail: nil, snapshot: snapshot)
        }
        return nil
    }

    static func isImageFile(_ url: URL) -> Bool {
        UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) ?? false
    }

    /// A single line that is just a URL, a file name/path, or a token with no spaces.
    static func looksLikeImageReference(_ text: String) -> Bool {
        guard text.count <= 2048, !text.contains(where: \.isNewline) else { return false }
        let lower = text.lowercased()
        if ["http://", "https://", "file://", "data:image"].contains(where: lower.hasPrefix) { return true }
        if let ext = text.split(separator: ".").last, UTType(filenameExtension: String(ext))?.conforms(to: .image) == true {
            return true
        }
        return !text.contains(where: \.isWhitespace)
    }

    /// Thumbnail of an image file on disk.
    public static func thumbnail(fileURL: URL, maxPixels: Int = 760) -> Data? {
        guard let data = try? Data(contentsOf: fileURL, options: .mappedIfSafe) else { return nil }
        return thumbnail(from: data, maxPixels: maxPixels)
    }

    /// Best plain-text form of the first item: plain string, else text extracted from RTF/RTFD/HTML.
    public static func plainText(from snapshot: PasteboardSnapshot) -> String? {
        let reps = snapshot.representations
        func data(_ uti: String) -> Data? { reps.first { $0.uti == uti }?.data }

        if let d = data(NSPasteboard.PasteboardType.string.rawValue), let s = String(data: d, encoding: .utf8) {
            return s
        }
        if let d = data("public.utf16-plain-text"), let s = String(data: d, encoding: .utf16) {
            return s
        }
        if let d = data(NSPasteboard.PasteboardType.rtf.rawValue),
           let a = try? NSAttributedString(data: d, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil) {
            return a.string
        }
        if let d = data(NSPasteboard.PasteboardType.rtfd.rawValue) ?? data("com.apple.flat-rtfd"),
           let a = try? NSAttributedString(data: d, options: [.documentType: NSAttributedString.DocumentType.rtfd], documentAttributes: nil) {
            return a.string
        }
        if let d = data(NSPasteboard.PasteboardType.html.rawValue), let html = String(data: d, encoding: .utf8) {
            // The HTML importer needs the main thread (WebKit); a tag strip is enough for a label.
            return stripHTML(html)
        }
        return nil
    }

    static func stripHTML(_ html: String) -> String {
        var s = html.replacingOccurrences(of: "<(script|style)[^>]*>[\\s\\S]*?</\\1>", with: "", options: .regularExpression)
        s = s.replacingOccurrences(of: "<br\\s*/?>|</p>|</div>|</li>", with: "\n", options: [.regularExpression, .caseInsensitive])
        s = s.replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
        let entities = ["&nbsp;": " ", "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": "\"", "&#39;": "'"]
        for (k, v) in entities { s = s.replacingOccurrences(of: k, with: v) }
        return s.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// The image representation used for the thumbnail and duplicate hash.
    static func primaryImage(in snapshot: PasteboardSnapshot) -> Representation? {
        let preferred = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"]
        for uti in preferred {
            if let rep = snapshot.representations.first(where: { $0.uti == uti }) { return rep }
        }
        return snapshot.representations.first { UTType($0.uti)?.conforms(to: .image) == true }
    }

    /// Downscaled PNG (longest side ≤ `maxPixels`) for the 84pt-tall image row preview.
    public static func thumbnail(from imageData: Data, maxPixels: Int = 760) -> Data? {
        guard let source = CGImageSourceCreateWithData(imageData as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, cg, nil)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return out as Data
    }

    static func digest(_ string: String) -> String {
        digest(Data(string.utf8), prefix: "")
    }

    static func digest(_ data: Data, prefix: String) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(prefix.utf8))
        hasher.update(data: data)
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
